export type Command = {
  id: string;
  /** 最优解，出题只考它 */
  display: string;
  desc: string;
  /** 这条命令在哪些 mode 有效（同一命令常在 n/v/x 各注册一条） */
  modes: string[];
  group: string;
  groupLabel: string;
  /** 是否落在 which-key 的分组树里（/seq 按它区分「真分组」和「兜底桶」） */
  inWhichKey: boolean;
  /** which-key 的原始分组名。true = 插件自动推断的 */
  wkGroup: string | true | null;
  /** 次解：实测同一条命令的其它键。仅展示 */
  alternates: string[];
  /** 等价判据：rhs = 严格实测，desc = 弱（Lua 回调只能按描述归类），lone = 没聚合 */
  equivBy: "rhs" | "desc" | "lone";
  /** 原生 Ex 等价。null = 确认没有（插件功能） */
  native: string | null;
  /** 原生等价核实过没有 */
  nativeVerified: true | "unchecked";
  /** 这道命令总共有几个键能做 */
  total: number;
};
